"""Generate the weekly digest post from raw feed data via OpenRouter.

Reads reports/pending.json (filled daily by news-aggregator), sends it with prompts/digest.md to the
OpenRouter Responses API (with the web-search server tool enabled), writes the
result to content/posts/YYYY-MM-DD.md, appends the run's cost to
data/costs.json, and clears the pending buffer.

Environment:
    OPENROUTER_API_KEY  required
    OPENROUTER_MODEL    model slug (default: DEFAULT_MODEL)
"""

from __future__ import annotations

import json
import logging
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

import httpx

from news_aggregator.aggregate import PENDING_FILE

log = logging.getLogger(__name__)

REPO_ROOT = Path(__file__).resolve().parents[2]
POSTS_DIR = REPO_ROOT / "content" / "posts"
COSTS_FILE = REPO_ROOT / "data" / "costs.json"
PROMPT_FILE = REPO_ROOT / "prompts" / "digest.md"

API_URL = "https://openrouter.ai/api/v1/responses"
DEFAULT_MODEL = "deepseek/deepseek-v4.1-flash-1017"


def build_request(model: str, entries: list[dict], now: datetime) -> dict:
    user = (
        f"Today is {now:%A, %B %-d, %Y}. Use date: {now:%Y-%m-%dT%H:%M:%SZ} in the front matter.\n"
        f"Here are {len(entries)} feed entries from the last 7 days:\n\n"
        + json.dumps(entries, indent=1)
    )
    return {
        "model": model,
        "input": [
            {"type": "message", "role": "system", "content": [{"type": "input_text", "text": PROMPT_FILE.read_text()}]},
            {"type": "message", "role": "user", "content": [{"type": "input_text", "text": user}]},
        ],
        "tools": [{"type": "openrouter:web_search", "parameters": {"max_results": 8, "max_uses": 6}}],
        "max_output_tokens": 32000,
    }


def call_openrouter(payload: dict, api_key: str) -> dict:
    resp = httpx.post(
        API_URL,
        json=payload,
        headers={"Authorization": f"Bearer {api_key}", "X-Title": "news-aggregator"},
        timeout=600,
    )
    if resp.is_error:
        # Print only the message: the body also carries the account's user_id, and CI logs are public.
        try:
            message = resp.json()["error"]["message"]
        except (ValueError, KeyError, TypeError):
            message = resp.text[:500]
        sys.exit(f"OpenRouter returned {resp.status_code}: {message}")
    return resp.json()


def extract_text(response: dict) -> str:
    """Concatenate output_text parts of the final assistant message(s)."""
    parts = [
        c["text"]
        for item in response.get("output", [])
        if item.get("type") == "message"
        for c in item.get("content", [])
        if c.get("type") == "output_text"
    ]
    return "".join(parts).strip()


def finalize_post(text: str, model: str, now: datetime) -> str:
    """Strip stray code fences, validate front matter, and append the footer."""
    if text.startswith("```"):
        text = text.split("\n", 1)[1].rsplit("```", 1)[0].strip()
    # Drop numeric citation markers like "[1.1.7]" leaked from web-search annotations.
    text = re.sub(r" ?\[\d+(?:\.\d+)*\](?!\()", "", text)
    if not text.startswith("---"):
        raise ValueError(f"Model output has no front matter: {text[:200]!r}")
    return f"{text}\n\n---\n\n*Generated by {model} via OpenRouter · {now:%Y-%m-%d %H:%M UTC}*\n"


def cost_record(response: dict, model: str, now: datetime) -> dict:
    usage = response.get("usage") or {}
    return {
        "date": now.strftime("%Y-%m-%d"),
        "timestamp": now.isoformat(),
        "model": model,
        "cost_usd": usage.get("cost"),
        "input_tokens": usage.get("input_tokens"),
        "output_tokens": usage.get("output_tokens"),
        "cache_read_tokens": (usage.get("input_tokens_details") or {}).get("cached_tokens"),
        "web_searches": (usage.get("server_tool_use_details") or {}).get("web_search_requests"),
    }


def record_cost(record: dict) -> None:
    """Append to data/costs.json and publish a summary line for the workflow."""
    history = json.loads(COSTS_FILE.read_text()) if COSTS_FILE.exists() else []
    history.append(record)
    COSTS_FILE.write_text(json.dumps(history, indent=2) + "\n")

    total = sum(r["cost_usd"] for r in history if isinstance(r.get("cost_usd"), (int, float)))
    cost = record["cost_usd"]
    cost_line = (
        f"Cost: {f'${cost:.4f}' if cost is not None else 'n/a'} · "
        f"{(record['input_tokens'] or 0) + (record['output_tokens'] or 0):,} tokens · "
        f"{record['web_searches'] or 0} searches · {record['model']} "
        f"(total to date: ${total:.2f})"
    )
    log.info(cost_line)
    if path := os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(path, "a") as f:
            f.write(f"### 💸 Run cost\n\n{cost_line}\n")
    if path := os.environ.get("GITHUB_OUTPUT"):
        with open(path, "a") as f:
            f.write(f"cost_line={cost_line}\n")


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    api_key = os.environ.get("OPENROUTER_API_KEY")
    if not api_key:
        sys.exit("OPENROUTER_API_KEY is not set")
    model = os.environ.get("OPENROUTER_MODEL") or DEFAULT_MODEL
    now = datetime.now(timezone.utc)

    entries = json.loads(PENDING_FILE.read_text()) if PENDING_FILE.exists() else []
    if not entries:
        sys.exit("reports/pending.json is empty; run news-aggregator first")
    log.info("Generating digest from %d pending entries with %s", len(entries), model)

    response = call_openrouter(build_request(model, entries, now), api_key)
    record_cost(cost_record(response, model, now))

    post = finalize_post(extract_text(response), model, now)
    out_file = POSTS_DIR / f"{now:%Y-%m-%d}.md"
    out_file.write_text(post)
    PENDING_FILE.write_text("[]\n")
    log.info("Wrote %s and cleared pending buffer", out_file)


if __name__ == "__main__":
    main()
