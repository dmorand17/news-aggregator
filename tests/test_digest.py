from datetime import datetime, timezone

import pytest

from news_aggregator.digest import build_request, cost_record, extract_text, finalize_post

NOW = datetime(2026, 11, 20, 18, 0, tzinfo=timezone.utc)

RESPONSE = {
    "output": [
        {"type": "web_search_call", "status": "completed"},
        {
            "type": "message",
            "role": "assistant",
            "content": [{"type": "output_text", "text": "---\ntitle: \"T\"\n---\n\nBody", "annotations": []}],
        },
    ],
    "usage": {
        "input_tokens": 1000,
        "output_tokens": 200,
        "cost": 0.0123,
        "input_tokens_details": {"cached_tokens": 50},
        "server_tool_use_details": {"web_search_requests": 3},
    },
}


def test_extract_text_reads_message_output():
    assert extract_text(RESPONSE) == '---\ntitle: "T"\n---\n\nBody'


def test_finalize_post_appends_footer():
    post = finalize_post('---\ntitle: "T"\n---\n\nBody', "x/model", NOW)
    assert post.startswith("---\ntitle")
    assert post.endswith("*Generated by x/model via OpenRouter · 2026-11-20 18:00 UTC*\n")


def test_finalize_post_strips_code_fence():
    assert finalize_post('```markdown\n---\ntitle: "T"\n---\nBody\n```', "m", NOW).startswith("---")


def test_finalize_post_strips_citation_markers():
    post = finalize_post('---\ntitle: "T"\n---\n\nSaid so [1.1.7]. See [2](https://x.y) [3].', "m", NOW)
    assert "Said so. See [2](https://x.y)." in post


def test_finalize_post_rejects_missing_front_matter():
    with pytest.raises(ValueError):
        finalize_post("Sorry, I can't do that.", "m", NOW)


def test_cost_record_maps_usage():
    rec = cost_record(RESPONSE, "x/model", NOW)
    assert rec["date"] == "2026-11-20"
    assert rec["cost_usd"] == 0.0123
    assert (rec["input_tokens"], rec["output_tokens"]) == (1000, 200)
    assert rec["cache_read_tokens"] == 50
    assert rec["web_searches"] == 3


def test_cost_record_tolerates_missing_usage():
    assert cost_record({}, "m", NOW)["cost_usd"] is None


def test_build_request_enables_web_search():
    req = build_request("x/model", [{"title": "a"}], NOW)
    assert req["tools"][0]["type"] == "openrouter:web_search"
    assert "2026-11-20T18:00:00Z" in req["input"][1]["content"][0]["text"]


def _fake_post(status, body):
    import httpx

    def post(url, **kwargs):
        return httpx.Response(status, json=body, request=httpx.Request("POST", url))

    return post


def test_call_openrouter_returns_json(monkeypatch):
    from news_aggregator import digest

    monkeypatch.setattr(digest.httpx, "post", _fake_post(200, RESPONSE))
    assert digest.call_openrouter({}, "key") == RESPONSE


def test_call_openrouter_exits_with_error_body(monkeypatch):
    from news_aggregator import digest

    monkeypatch.setattr(digest.httpx, "post", _fake_post(400, {"error": {"message": "bad model"}}))
    with pytest.raises(SystemExit, match="400.*bad model"):
        digest.call_openrouter({}, "key")
